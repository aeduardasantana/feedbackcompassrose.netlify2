create or replace function public.next_operational_code(prefix text, sequence_name text)
returns text
language plpgsql
as $$
declare
  sequence_value bigint;
begin
  execute format('select nextval(%L)', sequence_name) into sequence_value;
  return prefix || '-' || lpad(sequence_value::text, 3, '0');
end;
$$;

create sequence if not exists public.empresas_codigo_operacional_seq;
create sequence if not exists public.processos_codigo_operacional_seq;
create sequence if not exists public.matrizes_relacionais_codigo_operacional_seq;
create sequence if not exists public.avaliacoes_codigo_operacional_seq;

create table if not exists public.global_admin_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  nome text,
  role text not null default 'global_admin',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint global_admin_profiles_role_check check (role = 'global_admin')
);

alter table public.global_admin_profiles enable row level security;

create policy "global admins can read own profile"
  on public.global_admin_profiles
  for select
  to authenticated
  using (auth.uid() = id);

create policy "global admins can update own profile"
  on public.global_admin_profiles
  for update
  to authenticated
  using (auth.uid() = id)
  with check (auth.uid() = id);

create table if not exists public.processo_tokens (
  id bigint generated by default as identity primary key,
  processo_id text not null,
  token_hash text not null unique,
  descricao text,
  expires_at timestamptz,
  ativo boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.questionario_tokens (
  id bigint generated by default as identity primary key,
  questionario_id text not null,
  avaliador_nome text not null,
  avaliador_email text,
  token_hash text not null unique,
  descricao text,
  respondido boolean not null default false,
  respondido_at timestamptz,
  expires_at timestamptz,
  ativo boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.processo_tokens enable row level security;
alter table public.questionario_tokens enable row level security;

create policy "authenticated admins can manage processo tokens"
  on public.processo_tokens
  for all
  to authenticated
  using (exists (
    select 1 from public.global_admin_profiles
    where id = auth.uid() and role = 'global_admin'
  ))
  with check (exists (
    select 1 from public.global_admin_profiles
    where id = auth.uid() and role = 'global_admin'
  ));


  id uuid primary key,
  codigo_operacional text not null default public.next_operational_code('EMP', 'public.empresas_codigo_operacional_seq'),
  nome text not null,
  cnpj text,
  setor text,
  responsavel text,
  email text,
  telefone text,
  endereco text,
  consultora_id uuid not null references public.consultoras(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

